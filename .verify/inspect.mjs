import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const loaded = [];
globalThis.window = { __ModuleLoader__: { load(d) { loaded.push(d); } } };
globalThis.document = { baseURI: 'http://127.0.0.1:11834/' };
globalThis.fetch = async () => { throw new Error('offline'); };
globalThis.requestAnimationFrame = (cb) => setTimeout(cb, 16);
globalThis.cancelAnimationFrame = (id) => clearTimeout(id);
vm.runInThisContext(readFileSync(new URL('../client.js', import.meta.url), 'utf8'), { filename: 'client.js' });
const mod = loaded[0].factory(require);
const regs = [];
mod.apply({ slots: { inject(n, cb) { cb(); }, register(spec, component) { regs.push({ spec, component }); } } });
const main = regs.find((r) => r.spec.name === 'main').component;
const html = renderToStaticMarkup(React.createElement(main, {}));
const body = html.replace(/<style>[\s\S]*?<\/style>/g, '');
console.log('lanes:', (body.match(/yq-lane/g) || []).length, 'swim:', (body.match(/yq-swim/g) || []).length);
console.log('buttons:', (body.match(/yq-ghost|yq-primary/g) || []).length);
console.log((body.match(/<header[\s\S]*?<\/header>/) || [''])[0].replace(/></g, '>\n<'));
